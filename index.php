/* ---------- CSS Selector → XPath (copy of the one in fetch.php) ---------- */
function cssToXPath(string $css): string {
  $parts = preg_split('/\s*>\s*/', trim($css));
  $xp = '';
  foreach ($parts as $part) {
    $seg = '*';
    if (preg_match('/^([a-z0-9]*)#([\w-]+)/i', $part, $m)) {
      $tag = $m[1] ?: '*';
      $seg = $tag . '[@id="' . $m[2] . '"]';
    } elseif (preg_match('/^([a-z0-9]*)\.([\w-]+)/i', $part, $m)) {
      $tag = $m[1] ?: '*';
      $seg = $tag . '[contains(concat(" ", normalize-space(@class), " "), " ' . $m[2] . ' ")]';
    } elseif (preg_match('/^([a-z0-9*]+):nth-of-type\((\d+)\)$/i', $part, $m)) {
      $seg = $m[1] . '[' . $m[2] . ']';
    } elseif (preg_match('/^[a-z0-9*]+$/i', $part)) {
      $seg = $part;
    }
    $xp .= ($xp === '' ? '' : '/') . $seg;
  }
  return '//' . $xp;
}

/* ---------- PHP snippet generator (standalone, only needs cURL + DOM) ---------- */
function buildPhpSnippet(string $url, string $selector): string {
  $xpath = cssToXPath($selector);

  $tpl = <<<'PHP'
<?php
/**
 * Auto-generated by Selector Picker
 * ---------------------------------------------------------------
 * Just drop this file on any PHP host (5.4+) and call it.
 * Returns the extracted text, or null on failure.
 *
 * Usage:
 *   $price = require 'price.php';
 *   echo $price;
 */

$url      = %s;
$selector = %s;   // XPath (converted from the CSS selector you picked)

$ch = curl_init($url);
curl_setopt_array($ch, [
    CURLOPT_RETURNTRANSFER => true,
    CURLOPT_FOLLOWLOCATION => true,
    CURLOPT_MAXREDIRS      => 5,
    CURLOPT_TIMEOUT        => 25,
    CURLOPT_USERAGENT      => 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36',
    CURLOPT_HTTPHEADER     => [
        'Accept: text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8',
        'Accept-Language: en-US,en;q=0.9',
    ],
    CURLOPT_ENCODING       => '',
    CURLOPT_SSL_VERIFYPEER => false,
    CURLOPT_SSL_VERIFYHOST => false,
]);
$html = curl_exec($ch);
curl_close($ch);

if ($html === false || $html === '') {
    return null;
}

libxml_use_internal_errors(true);
$doc = new DOMDocument();
$doc->loadHTML('<?xml encoding="UTF-8">' . $html);
$xpath = new DOMXPath($doc);

$nodes = $xpath->query($selector);
$value = ($nodes && $nodes->length)
    ? trim(preg_replace('/\s+/', ' ', $nodes->item(0)->textContent))
    : null;

return $value;
PHP;

  return sprintf($tpl, var_export($url, true), var_export($xpath, true));
}

