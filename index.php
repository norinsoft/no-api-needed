function isLikelyUrl(s){
  s = s.trim();
  if (!s) return false;
  if (/^https?:\/\//i.test(s)) return true;
  if (/\s/.test(s)) return false;
  return /^[\w-]+(\.[\w-]+)+([\/?#].*)?$/i.test(s);
}
function normalizeUrl(s){
  s = s.trim();
  return /^https?:\/\//i.test(s) ? s : 'https://' + s;
}

